; Плагины типа #06: выполняются один раз после инициализации Wild Commander.
;
; Штатные типы #00..#05 и #11..#15 уже заняты ABI плагинов. В частности,
; #01 означает запуск после ручной загрузки, а #04 — меню выбора вьювера.
; Свободный #06 при разборе [PLUGINS] только регистрируется: ALPL не передаёт
; его ни RAJT, ни EDTPR. После автозапуска его заголовок удаляется из обычной
; таблицы плагинов, поэтому в пользовательское меню он не попадает.
;
; Автозапуск выполняет этот отдельный проход — уже после того, как интерфейс
; построен. Вызов подставлен вместо CALL WCINI.PATH в MD20: PATH выполняется
; следом и восстанавливает каталоги и позиции обеих панелей.
;
; Код лежит в нулевой области перед #C000, поэтому ни один точный модуль не
; сдвигается: границы MD20, WCINI и остальных остаются прежними.

; Точки WCVW и WCVLS объявлены внутри своих модулей и снаружи не видны,
; поэтому повторяются здесь под своими именами. Адреса фиксированные:
; их держат ассерты границ в BOOT.ASM.
AX_PLHPG EQU #60                        ; страница заголовков плагинов
AX_MNGC  EQU #68C1                      ; подключить страницу к окну #C000
AX_LOBU  EQU #B000                      ; буфер заголовка для запуска
AX_AJT   EQU #70C3                      ; выполнить плагин из AX_LOBU
AX_TYPE  EQU #06                        ; новый, ранее свободный тип автозапуска
FILEX_PROVIDER_PAGE_ADDR EQU #6A48      ; операнд LD A,#page в резидентном шлюзе
FILEX_PROVIDER_ENTRY     EQU #C010      ; постоянный вход в подключённой странице

; Замена CALL WCINI.PATH в последовательности старта: тот же размер вызова.
AX_PATH:
        CALL AX_RUN
        JP WCINI.PATH

; Обойти заголовки загруженных плагинов, выполнить каждый с типом #06 и сразу
; убрать его заголовок из таблицы, которую F11MENU показывает пользователю.
AX_RUN:
; Claude - 2026-10-10 - begin
        ; FILEX.WMF обязателен: в нём часть расширения ядра (оверлей). Нет его
        ; или он от другой сборки — сообщение и HALT до первого плагина #06.
        CALL WDOS_EXT.FILEX_REQUIRED
; Claude - 2026-10-10 - end
        ; Ноль в непосредственном операнде шлюза означает, что обязательный
        ; FILEX.WMF ещё не зарегистрировался. Менеджер плагинов не может
        ; затереть этот байт как обычную переменную состояния.
        XOR A
        LD (FILEX_PROVIDER_PAGE_ADDR),A
        ; PPGM — логический номер страницы плагина, а не текущее физическое
        ; отображение окна #C000. MNGC хранит фактическую страницу в #6003.
        ; Сохраняем именно её: следом идёт PATH, которому нужно прежнее окно.
        LD A,(#6003)
        PUSH AF
; Перебор — WCVW.HNEXT: полная таблица (32 заголовка, PHED=#0000) прежде
; кончалась сразу, и ни один #06 не выполнялся. После каждого выполненного
; плагина его заголовок удаляется, а таблица просматривается с начала.
AX_RESCAN:
        LD A,AX_PLHPG
        CALL AX_MNGC                    ; страница заголовков (плагин мог сменить)
        LD DE,#C000+197-512             ; байт типа «предыдущего» заголовка
AX_SCAN:
        CALL WCVW.HNEXT
        JR C,AX_DONE                    ; заголовки кончились
        LD A,(DE)
        CP AX_TYPE
        JR NZ,AX_SCAN

        EX DE,HL
        LD BC,0-197
        ADD HL,BC                       ; начало найденного заголовка
        PUSH HL                         ; адрес удаляемого слота переживает плагин
        LD DE,AX_LOBU
        LD BC,256
        LDIR
        CALL AX_AJT                     ; выполнить плагин
        POP HL
        CALL AX_REMOVE_HEADER           ; в меню типа #06 больше нет
        JR AX_RESCAN

; Удалить 512-байтовый заголовок по HL, сохранив порядок остальных плагинов.
; Страницы самого одноразового плагина не перемещаются: после возврата из него
; они больше не нужны, а PPGM остаётся совместимым со штатным менеджером памяти.
; Длина хвоста — PHED минус следующий заголовок по модулю #10000: верна и для
; полной таблицы (PHED=#0000). Окно #C000 — страница заголовков.
AX_REMOVE_HEADER:
        ; Плагин оставляет в окне #C000 свою страницу: без возврата страницы
        ; заголовков сдвигалась чужая память, PHED уменьшался, а таблица — нет,
        ; и тот же #06 запускался снова, пока PHED не доходил до #C000 (стенд
        ; unreal-ng, 2026-10-10).
        PUSH HL
        LD A,AX_PLHPG
        CALL AX_MNGC
        POP HL
        PUSH HL                         ; приёмник — удаляемый слот
        INC H
        INC H                           ; источник: следующий заголовок
        EX DE,HL
        LD HL,(PHED)                    ; прежний конец таблицы
        OR A
        SBC HL,DE                       ; длина хвоста после удаляемого слота
        LD B,H
        LD C,L
        EX DE,HL                        ; HL — источник
        POP DE                          ; DE — приёмник
        LD A,B
        OR C
        JR Z,AX_HEADER_MOVED            ; LDIR с BC=0 скопировал бы 65536 байт
        LDIR
AX_HEADER_MOVED:
        LD (PHED),DE                    ; новый конец на 512 байт ниже
        RET

; Вернуть фактическое отображение окна #C000. PPGM мы не меняли.
AX_DONE:
        POP AF
        JP AX_MNGC
        IF $ < #BFD4
        DS #BFD4-$,0                    ; INIT_RELOCATED — на прежнем месте
        ENDIF

; Первые 39 байтов INIT нужны только до загрузки плагинов. Их перенос в
; свободный хвост освобождает постоянный диапазон #6A47..#6A6A под FILEX,
; не меняя адреса INIT, L6011_139, TURBO и последующих процедур.
INIT_RELOCATED:
        LD      BC,#00AF
        LD      A,#30
        OUT     (C),A
        LD      BC,#EFF7
        LD      A,#80
        OUT     (C),A
        LD      B,#DF
        LD      A,#0B
        OUT     (C),A
        LD      B,#BF
        XOR     A
        OUT     (C),A
        LD      B,#DF
        LD      A,#0C
        OUT     (C),A
        LD      B,#BF
        LD      A,#01
        OUT     (C),A
        LD      B,#DF
        JP      INIT_CONTINUE
        DS      #BFFF-$,0
        IFNDEF WDOS_SYMBOL_PASS
        ASSERT  INIT_RELOCATED == #BFD4, изменился адрес перенесённого INIT
        ASSERT  $ == #BFFF, изменился размер перенесённого INIT
        ; Claude - 2026-10-10: FILEX_REQUIRED (CORE32_EXT.ASM) зовёт их по адресам.
        ASSERT  PRWOW == #792C && PRSRW == #7D25 && PRIAT == #7D39, сдвинулись входы WCIF
        ; Claude - 2026-10-11: ZCG_RECOVER и MEDIA_IDLE_CODE (CORE32_EXT.ASM, WC_*).
        ASSERT  RRESB == #7ACE && CURSOR == #7CD5 && DRACT == #6868 && L6011_46 == #63ED, сдвинулись входы WC для вынутой карты
        ASSERT  WINDOW == #7EA0 && WINDO2 == #7EC4, сдвинулись описатели панелей
        ASSERT  Xpan == #6149 && WCFX.STATUS == #8723, сдвинулись Xpan или STATUS
        ENDIF
