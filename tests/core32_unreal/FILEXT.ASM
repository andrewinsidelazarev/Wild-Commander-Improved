; Автономный исполняемый тест публичного API 77 FILEX для patched Unreal.
; Все файловые операции идут через #6006; прямой доступ к странице CORE32
; используется только тестовым счётчиком чтений и инъекцией отказов драйвера.

        DEVICE ZXSPECTRUM128

        MODULE FILEX_TEST_WDOS
        INCLUDE "../../Build/CORE32_WDOS_SYMBOLS.INC"
        ENDMODULE
        INCLUDE "../../source/CORE32_FILEX_API.ASM"

WLD                     EQU #6006
CORE_PAGE_IN            EQU #6B7A
CORE_PAGE_OUT           EQU #6B8B
DRIVER_RDD_JUMP         EQU #380F
DRIVER_SDD_JUMP         EQU #3812
DRIVER_ABT              EQU #384A
DRIVER_BLKNUM           EQU #38D0

RESULT_STATUS           EQU RESULT_BUFFER+8
RESULT_FAILED_TEST      EQU RESULT_BUFFER+9
RESULT_API_ERROR        EQU RESULT_BUFFER+10
RESULT_STAGE            EQU RESULT_BUFFER+11
RESULT_COMPLETED        EQU RESULT_BUFFER+12
RESULT_READ_CALLS       EQU RESULT_BUFFER+13
RESULT_FAULT_CAT        EQU RESULT_BUFFER+14
RESULT_FAULT_META       EQU RESULT_BUFFER+15
RESULT_FAULT_FAT        EQU RESULT_BUFFER+16
RESULT_FAULT_FSINFO     EQU RESULT_BUFFER+17
RESULT_FS_COPY          EQU RESULT_BUFFER+32

FAIL_MODE_EXACT         EQU 1
FAIL_MODE_FAT           EQU 2

        ORG #0000
START_CODE:
        DS 16,0
        DB "WildCommanderMDL"
        DB #0A
        DB #00
        DB #01
        DB #00
        DB #00,(PLUGIN_FILE_END-MAIN_FILE_START+511)/512
        DB #00,#00
        DB #00,#00
        DB #00,#00
        DB #00,#00
        DB #00,#00
        DS 16,0
        DS 32*3,0
        DB #00
        DD #FFFFFFFF
FILEXT_PLUGIN_NAME:
        DB "FILEX API 77 regression test"
        DS 32-($-FILEXT_PLUGIN_NAME)," "
        ; Провайдер и CORE32T используют одноразовый тип #06. Сам FILEXT
        ; оставляем штатным пунктом меню #03: patched Unreal запускает его
        ; детерминированно через F10/Enter после установки провайдера.
        DB #03
        DB #00

        ALIGN 512,0
MAIN_FILE_START:
        DISP #8000

PLUGIN:
        PUSH IX
        CALL GEDPL
        ; Клонировать поток панели и перейти в корень независимо от wc.ini.
        LD D,#FE:CALL STREAM_API
        LD D,#FF:CALL STREAM_API
        CALL INITIALIZE_RESULT
        CALL ENTER_TEST_DIRECTORY
        JR Z,.directory_ready
        LD B,#E0
        LD A,#FD
        JP TEST_FAILED
.directory_ready:
        LD A,1:CALL CHECKPOINT
        JP NZ,INFRASTRUCTURE_FAILED

        CALL TEST_ABI_AND_FSINFO
        JR Z,.test1_ok
        LD B,1:JP TEST_FAILED
.test1_ok:
        LD A,1:LD (RESULT_COMPLETED),A
        LD A,2:CALL CHECKPOINT
        JP NZ,INFRASTRUCTURE_FAILED

        CALL TEST_POSITIONAL_READ
        JR Z,.test2_ok
        LD B,2:JP TEST_FAILED
.test2_ok:
        LD A,2:LD (RESULT_COMPLETED),A
        LD A,3:CALL CHECKPOINT
        JP NZ,INFRASTRUCTURE_FAILED

        CALL TEST_POSITIONAL_WRITE
        JR Z,.test3_ok
        LD B,3:JP TEST_FAILED
.test3_ok:
        LD A,3:LD (RESULT_COMPLETED),A
        LD A,4:CALL CHECKPOINT
        JP NZ,INFRASTRUCTURE_FAILED

        CALL TEST_SET_EOF
        JR Z,.test4_ok
        LD B,4:JP TEST_FAILED
.test4_ok:
        LD A,4:LD (RESULT_COMPLETED),A
        LD A,5:CALL CHECKPOINT
        JP NZ,INFRASTRUCTURE_FAILED

        CALL TEST_MOVE_RENAME
        JR Z,.test5_ok
        LD B,5:JP TEST_FAILED
.test5_ok:
        LD A,5:LD (RESULT_COMPLETED),A
        LD A,6:CALL CHECKPOINT
        JP NZ,INFRASTRUCTURE_FAILED

        CALL TEST_METADATA
        JR Z,.test6_ok
        LD B,6:JP TEST_FAILED
.test6_ok:
        LD A,6:LD (RESULT_COMPLETED),A
        LD A,7:CALL CHECKPOINT
        JP NZ,INFRASTRUCTURE_FAILED

        CALL TEST_FAULT_ROLLBACKS
        JR Z,.test7_ok
        LD B,7:JP TEST_FAILED
.test7_ok:
        LD A,7:LD (RESULT_COMPLETED),A
        LD A,#FF:LD (RESULT_STAGE),A
        LD A,1:LD (RESULT_STATUS),A
        CALL WRITE_RESULT
        JR Z,FINISH
INFRASTRUCTURE_FAILED:
        LD B,#EF
        LD A,#FC
TEST_FAILED:
        LD (RESULT_API_ERROR),A
        LD A,B:LD (RESULT_FAILED_TEST),A
        LD A,#FF:LD (RESULT_STATUS),A
        CALL WRITE_RESULT
FINISH:
        POP IX
        RET

INITIALIZE_RESULT:
        LD HL,RESULT_BUFFER,DE,RESULT_BUFFER+1,BC,511
        XOR A:LD (HL),A:LDIR
        LD HL,RESULT_SIGNATURE_BYTES,DE,RESULT_BUFFER,BC,8
        LDIR
        RET

CHECKPOINT:
        LD (RESULT_STAGE),A
        JP WRITE_RESULT

WRITE_RESULT:
        LD HL,RESULT_FIND
        CALL FENTRY
        JR Z,.not_found
        CALL GFILE
        LD HL,RESULT_BUFFER
        LD B,1
        CALL SAVE512
        RET C
        XOR A
        RET
.not_found:
        LD A,#FD:OR A:RET

; Найти FXT716, сохранить его кластер из TENTRY и войти в каталог.
ENTER_TEST_DIRECTORY:
        LD HL,TEST_DIRECTORY_FIND
        CALL FENTRY
        JR Z,.failed
        LD DE,ENTRY_BUFFER
        CALL TENTRY
        LD HL,(ENTRY_BUFFER+26),DE,(ENTRY_BUFFER+20)
        LD A,D:AND #0F:LD D,A
        LD (TEST_DIRECTORY_CLUSTER),HL
        LD (TEST_DIRECTORY_CLUSTER+2),DE
        CALL GDIR
        XOR A
        RET
.failed:
        LD A,1:OR A:RET

RETURN_TO_TEST_DIRECTORY:
        LD D,#FF:CALL STREAM_API
        JP ENTER_TEST_DIRECTORY

RESET_FILEX_BLOCK:
        LD HL,FILEX_BLOCK,DE,FILEX_BLOCK+1,BC,FILEX_BLOCK_SIZE-1
        XOR A:LD (HL),A:LDIR
        LD A,FILEX_BLOCK_SIZE:LD (FILEX_BLOCK+FILEX_P_SIZE),A
        LD A,FILEX_API_VERSION:LD (FILEX_BLOCK+FILEX_P_VERSION),A
        RET

; Дополнительно сверить, что A и поле status описывают один результат.
CALL_FILEX:
        LD HL,FILEX_BLOCK
        LD A,77
        CALL WLD
        PUSH AF
        LD B,A
        LD A,(FILEX_BLOCK+FILEX_P_STATUS)
        CP B:JR NZ,.mismatch
        POP AF
        RET
.mismatch:
        POP AF
        LD A,#FE:OR A:RET

TEST_ABI_AND_FSINFO:
        CALL RESET_FILEX_BLOCK
        LD A,FILEX_OP_QUERY_CAPS:LD (FILEX_BLOCK+FILEX_P_OPERATION),A
        CALL CALL_FILEX
        RET NZ
        LD A,(FILEX_BLOCK+FILEX_P_RESULT_COUNT):CP #FF:JP NZ,SEMANTIC_ERROR
        LD HL,(FILEX_BLOCK+FILEX_P_RESULT_COUNT+1)
        LD A,H:OR L:JP NZ,SEMANTIC_ERROR
        LD A,(FILEX_BLOCK+FILEX_P_RESULT_COUNT+3):OR A:JP NZ,SEMANTIC_ERROR
        LD A,(FILEX_BLOCK+FILEX_P_RESULT_FLAGS):CP FILEX_API_VERSION
        JP NZ,SEMANTIC_ERROR

        ; Неизвестный номер, версия и флаг обязаны иметь стабильные статусы.
        CALL RESET_FILEX_BLOCK
        LD A,FILEX_OP_COUNT:LD (FILEX_BLOCK+FILEX_P_OPERATION),A
        CALL CALL_FILEX
        CP FILEX_STATUS_BAD_OPERATION:JP NZ,SEMANTIC_ERROR
        CALL RESET_FILEX_BLOCK
        LD A,2:LD (FILEX_BLOCK+FILEX_P_VERSION),A
        CALL CALL_FILEX
        CP FILEX_STATUS_BAD_VERSION:JP NZ,SEMANTIC_ERROR
        CALL RESET_FILEX_BLOCK
        LD A,1:LD (FILEX_BLOCK+FILEX_P_FLAGS),A
        CALL CALL_FILEX
        CP FILEX_STATUS_BAD_BLOCK:JP NZ,SEMANTIC_ERROR

        ; Выходной буфер, пересекающий блок, не должен портить параметры.
        CALL RESET_FILEX_BLOCK
        LD A,FILEX_OP_GET_FS_INFO:LD (FILEX_BLOCK+FILEX_P_OPERATION),A
        LD HL,FILEX_BLOCK:LD (FILEX_BLOCK+FILEX_P_BUFFER),HL
        LD HL,FILEX_FS_SIZE:LD (FILEX_BLOCK+FILEX_P_LENGTH),HL
        CALL CALL_FILEX
        CP FILEX_STATUS_BAD_BUFFER:JP NZ,SEMANTIC_ERROR

        ; Неверный адрес самого блока возвращает BAD_BLOCK без записи по нему.
        LD HL,#7FFF
        LD A,77
        CALL WLD
        CP FILEX_STATUS_BAD_BLOCK:JP NZ,SEMANTIC_ERROR

        CALL RESET_FILEX_BLOCK
        LD A,FILEX_OP_GET_FS_INFO:LD (FILEX_BLOCK+FILEX_P_OPERATION),A
        LD HL,FSINFO_BUFFER:LD (FILEX_BLOCK+FILEX_P_BUFFER),HL
        LD HL,FILEX_FS_SIZE:LD (FILEX_BLOCK+FILEX_P_LENGTH),HL
        CALL CALL_FILEX
        RET NZ
        LD HL,(FILEX_BLOCK+FILEX_P_RESULT_COUNT)
        LD DE,FILEX_FS_SIZE
        OR A:SBC HL,DE:JP NZ,SEMANTIC_ERROR
        LD HL,(FSINFO_BUFFER+FILEX_FS_O_BYTES_PER_SECTOR)
        LD DE,512:OR A:SBC HL,DE:JP NZ,SEMANTIC_ERROR
        LD A,(FSINFO_BUFFER+FILEX_FS_O_FLAGS)
        AND FILEX_FS_FLAG_MEDIA_PRESENT:JP Z,SEMANTIC_ERROR
        LD A,(FSINFO_BUFFER+FILEX_FS_O_SECTORS_PER_CLUSTER)
        OR A:JP Z,SEMANTIC_ERROR
        LD H,A:LD L,0:ADD HL,HL
        LD A,H:OR L:JP Z,SEMANTIC_ERROR
        LD (CLUSTER_BYTES),HL
        LD HL,FSINFO_BUFFER,DE,RESULT_FS_COPY,BC,FILEX_FS_SIZE
        LDIR
        XOR A
        RET

TEST_POSITIONAL_READ:
        LD HL,FRAGMENTED_FIND
        CALL FENTRY
        JP Z,SEARCH_ERROR
        CALL INSTALL_READ_COUNTER
        LD HL,(CLUSTER_BYTES)
        LD DE,17:OR A:SBC HL,DE
        LD (TEMP_OFFSET),HL
        XOR A:LD (TEMP_OFFSET+2),A:LD (TEMP_OFFSET+3),A
        CALL RESET_FILEX_BLOCK
        LD A,FILEX_OP_READ_AT:LD (FILEX_BLOCK+FILEX_P_OPERATION),A
        LD HL,(TEMP_OFFSET):LD (FILEX_BLOCK+FILEX_P_OFFSET),HL
        LD HL,READ_BUFFER:LD (FILEX_BLOCK+FILEX_P_BUFFER),HL
        LD HL,100:LD (FILEX_BLOCK+FILEX_P_LENGTH),HL
        CALL CALL_FILEX
        PUSH AF
        CALL RESTORE_READ_COUNTER
        POP AF
        RET NZ
        LD A,(READ_CALLS):LD (RESULT_READ_CALLS),A
        CP 5:JP NC,SEMANTIC_ERROR
        CP 2:JP C,SEMANTIC_ERROR
        LD HL,(FILEX_BLOCK+FILEX_P_RESULT_COUNT),DE,100
        OR A:SBC HL,DE:JP NZ,SEMANTIC_ERROR
        LD HL,READ_BUFFER,BC,17,A,#B2
        CALL CHECK_PATTERN
        JP NZ,SEMANTIC_ERROR
        LD BC,83:LD A,#C3
        CALL CHECK_PATTERN
        JP NZ,SEMANTIC_ERROR

        ; Частичное чтение у EOF возвращает EOF и фактические 20 байт.
        LD HL,(CLUSTER_BYTES):ADD HL,HL
        LD DE,20:OR A:SBC HL,DE
        LD (TEMP_OFFSET),HL
        CALL RESET_FILEX_BLOCK
        LD A,FILEX_OP_READ_AT:LD (FILEX_BLOCK+FILEX_P_OPERATION),A
        LD HL,(TEMP_OFFSET):LD (FILEX_BLOCK+FILEX_P_OFFSET),HL
        LD HL,READ_BUFFER:LD (FILEX_BLOCK+FILEX_P_BUFFER),HL
        LD HL,64:LD (FILEX_BLOCK+FILEX_P_LENGTH),HL
        CALL CALL_FILEX
        CP FILEX_STATUS_EOF:JP NZ,SEMANTIC_ERROR
        LD HL,(FILEX_BLOCK+FILEX_P_RESULT_COUNT),DE,20
        OR A:SBC HL,DE:JP NZ,SEMANTIC_ERROR
        LD HL,READ_BUFFER,BC,20,A,#D4
        CALL CHECK_PATTERN
        JP NZ,SEMANTIC_ERROR

        LD HL,(CLUSTER_BYTES):ADD HL,HL
        LD (TEMP_OFFSET),HL
        CALL RESET_FILEX_BLOCK
        LD A,FILEX_OP_READ_AT:LD (FILEX_BLOCK+FILEX_P_OPERATION),A
        LD HL,(TEMP_OFFSET):LD (FILEX_BLOCK+FILEX_P_OFFSET),HL
        LD HL,READ_BUFFER:LD (FILEX_BLOCK+FILEX_P_BUFFER),HL
        LD HL,1:LD (FILEX_BLOCK+FILEX_P_LENGTH),HL
        CALL CALL_FILEX
        CP FILEX_STATUS_EOF:JP NZ,SEMANTIC_ERROR
        LD HL,(FILEX_BLOCK+FILEX_P_RESULT_COUNT)
        LD A,H:OR L:JP NZ,SEMANTIC_ERROR
        XOR A
        RET

; Вход: HL — начало, BC — длина, A — ожидаемый байт. Выходной HL продолжает
; указывать на следующий диапазон.
CHECK_PATTERN:
        LD D,A
.loop:
        LD A,(HL):CP D:JR NZ,.failed
        INC HL:DEC BC
        LD A,B:OR C:JR NZ,.loop
        XOR A
        RET
.failed:
        LD A,1:OR A:RET

FILL_PATTERN:
        LD D,A
.loop:
        LD (HL),D:INC HL:DEC BC
        LD A,B:OR C:JR NZ,.loop
        RET

TEST_POSITIONAL_WRITE:
        LD HL,WRITE_FIND
        CALL FENTRY
        JP Z,SEARCH_ERROR

        LD HL,WRITE_BUFFER,BC,20,A,#A1:CALL FILL_PATTERN
        LD HL,3:LD DE,0:LD BC,20
        CALL WRITE_CURRENT
        RET NZ

        LD HL,WRITE_BUFFER,BC,10,A,#B2:CALL FILL_PATTERN
        LD HL,509:LD DE,0:LD BC,10
        CALL WRITE_CURRENT
        RET NZ

        LD HL,WRITE_BUFFER,BC,20,A,#C3:CALL FILL_PATTERN
        LD HL,(CLUSTER_BYTES)
        LD DE,7:OR A:SBC HL,DE
        EX DE,HL
        LD HL,DE
        LD DE,0:LD BC,20
        CALL WRITE_CURRENT
        RET NZ

        LD HL,WRITE_BUFFER,BC,32,A,#D4:CALL FILL_PATTERN
        LD HL,(CLUSTER_BYTES):ADD HL,HL
        LD DE,8:OR A:SBC HL,DE
        EX DE,HL
        LD HL,DE
        LD DE,0:LD BC,32
        CALL WRITE_CURRENT
        RET NZ

        ; Повторное открытие доказывает опубликованный новый EOF и данные хвоста.
        LD HL,WRITE_FIND:CALL FENTRY:JP Z,SEARCH_ERROR
        LD HL,(CLUSTER_BYTES):ADD HL,HL
        LD DE,8:OR A:SBC HL,DE
        LD (TEMP_OFFSET),HL
        CALL RESET_FILEX_BLOCK
        LD A,FILEX_OP_READ_AT:LD (FILEX_BLOCK+FILEX_P_OPERATION),A
        LD HL,(TEMP_OFFSET):LD (FILEX_BLOCK+FILEX_P_OFFSET),HL
        LD HL,READ_BUFFER:LD (FILEX_BLOCK+FILEX_P_BUFFER),HL
        LD HL,32:LD (FILEX_BLOCK+FILEX_P_LENGTH),HL
        CALL CALL_FILEX
        RET NZ
        LD HL,READ_BUFFER,BC,32,A,#D4
        CALL CHECK_PATTERN
        JP NZ,SEMANTIC_ERROR
        XOR A
        RET

; Вход: DE:HL — offset, BC — длина; источник всегда WRITE_BUFFER.
WRITE_CURRENT:
        LD (TEMP_OFFSET),HL:LD (TEMP_OFFSET+2),DE
        LD (TEMP_LENGTH),BC
        CALL RESET_FILEX_BLOCK
        LD A,FILEX_OP_WRITE_AT:LD (FILEX_BLOCK+FILEX_P_OPERATION),A
        LD HL,(TEMP_OFFSET):LD (FILEX_BLOCK+FILEX_P_OFFSET),HL
        LD HL,(TEMP_OFFSET+2):LD (FILEX_BLOCK+FILEX_P_OFFSET+2),HL
        LD HL,WRITE_BUFFER:LD (FILEX_BLOCK+FILEX_P_BUFFER),HL
        LD HL,(TEMP_LENGTH):LD (FILEX_BLOCK+FILEX_P_LENGTH),HL
        CALL CALL_FILEX
        RET NZ
        LD HL,(FILEX_BLOCK+FILEX_P_RESULT_COUNT)
        LD DE,(TEMP_LENGTH)
        OR A:SBC HL,DE:JP NZ,SEMANTIC_ERROR
        LD HL,(FILEX_BLOCK+FILEX_P_RESULT_COUNT+2)
        LD A,H:OR L:JP NZ,SEMANTIC_ERROR
        XOR A
        RET

TEST_SET_EOF:
        LD HL,TRUNC_BEGIN_FIND,BC,1,DE,0:CALL SET_EOF_NAMED:RET NZ
        LD HL,TRUNC_MIDDLE_FIND,BC,513,DE,0:CALL SET_EOF_NAMED:RET NZ
        LD HL,TRUNC_SECTOR_FIND,BC,512,DE,0:CALL SET_EOF_NAMED:RET NZ
        LD HL,TRUNC_CLUSTER_FIND
        LD BC,(CLUSTER_BYTES),DE,0:CALL SET_EOF_NAMED:RET NZ
        LD HL,TRUNC_ZERO_FIND,BC,0,DE,0:CALL SET_EOF_NAMED:RET NZ
        ; Рост 13 -> 31 остаётся в уже выделенном кластере и не должен искать
        ; либо требовать новый свободный кластер.
        LD HL,GROW_ZERO_FIND,BC,31,DE,0
        CALL SET_EOF_NAMED
        RET NZ
        LD HL,(CLUSTER_BYTES),DE,37:ADD HL,DE
        LD B,H:LD C,L
        LD HL,GROW_ZERO_FIND,DE,0
        CALL SET_EOF_NAMED
        RET NZ

        LD HL,GROW_ZERO_FIND:CALL FENTRY:JP Z,SEARCH_ERROR
        CALL RESET_FILEX_BLOCK
        LD A,FILEX_OP_READ_AT:LD (FILEX_BLOCK+FILEX_P_OPERATION),A
        LD HL,13:LD (FILEX_BLOCK+FILEX_P_OFFSET),HL
        LD HL,READ_BUFFER:LD (FILEX_BLOCK+FILEX_P_BUFFER),HL
        LD HL,100:LD (FILEX_BLOCK+FILEX_P_LENGTH),HL
        CALL CALL_FILEX
        RET NZ
        LD HL,READ_BUFFER,BC,100:XOR A
        CALL CHECK_PATTERN
        JP NZ,SEMANTIC_ERROR
        XOR A
        RET

; Вход: HL — запрос FENTRY, DE:BC — новый EOF.
SET_EOF_NAMED:
        LD (TEMP_QUERY),HL
        LD (TEMP_TARGET),BC:LD (TEMP_TARGET+2),DE
        CALL FENTRY
        JP Z,SEARCH_ERROR
        CALL RESET_FILEX_BLOCK
        LD A,FILEX_OP_SET_EOF32:LD (FILEX_BLOCK+FILEX_P_OPERATION),A
        LD HL,(TEMP_TARGET):LD (FILEX_BLOCK+FILEX_P_OFFSET),HL
        LD HL,(TEMP_TARGET+2):LD (FILEX_BLOCK+FILEX_P_OFFSET+2),HL
        CALL CALL_FILEX
        RET NZ
        LD HL,(FILEX_BLOCK+FILEX_P_RESULT_COUNT)
        LD DE,(TEMP_TARGET):OR A:SBC HL,DE:JP NZ,SEMANTIC_ERROR
        LD HL,(FILEX_BLOCK+FILEX_P_RESULT_COUNT+2)
        LD DE,(TEMP_TARGET+2):OR A:SBC HL,DE:JP NZ,SEMANTIC_ERROR
        XOR A
        RET

TEST_MOVE_RENAME:
        ; Получить кластеры родителей из их 32-байтовых ENTRY.
        LD HL,SOURCE_DIRECTORY_FIND
        LD DE,SOURCE_DIRECTORY_CLUSTER
        CALL CAPTURE_DIRECTORY_CLUSTER
        RET NZ
        LD HL,DEST_DIRECTORY_FIND
        LD DE,DEST_DIRECTORY_CLUSTER
        CALL CAPTURE_DIRECTORY_CLUSTER
        RET NZ

        ; Для запрета цикла нужен кластер CHILD внутри SRC/CYCLE.
        LD HL,SOURCE_DIRECTORY_FIND:CALL FENTRY:JP Z,SEARCH_ERROR
        CALL GDIR
        LD HL,CYCLE_DIRECTORY_FIND:CALL FENTRY:JP Z,SEARCH_ERROR
        CALL GDIR
        LD HL,CHILD_DIRECTORY_FIND
        LD DE,CHILD_DIRECTORY_CLUSTER
        CALL CAPTURE_DIRECTORY_CLUSTER
        RET NZ
        CALL RETURN_TO_TEST_DIRECTORY
        JP NZ,SEARCH_ERROR

        ; CURRENT_DIR обязан игнорировать переданные cluster32 и атомарно
        ; заменить файл непосредственно в активном каталоге WildDOS.
        LD HL,CURRENT_SOURCE_FIND:LD (MOVE_SOURCE_POINTER),HL
        LD HL,CURRENT_SOURCE_FIND_END-CURRENT_SOURCE_FIND
        LD (MOVE_SOURCE_LENGTH),HL
        LD HL,CURRENT_DEST_FIND:LD (MOVE_DEST_POINTER),HL
        LD HL,CURRENT_DEST_FIND_END-CURRENT_DEST_FIND
        LD (MOVE_DEST_LENGTH),HL
        LD HL,#FFFF
        LD (MOVE_SOURCE_DIRECTORY),HL:LD (MOVE_SOURCE_DIRECTORY+2),HL
        LD (MOVE_DEST_DIRECTORY),HL:LD (MOVE_DEST_DIRECTORY+2),HL
        LD A,FILEX_FLAG_REPLACE|FILEX_FLAG_CURRENT_DIR:LD (MOVE_FLAGS),A
        CALL DO_MOVE
        RET NZ

        CALL PREPARE_STANDARD_MOVE
        LD HL,MOVE_SOURCE_FIND:LD (MOVE_SOURCE_POINTER),HL
        LD HL,MOVE_SOURCE_FIND_END-MOVE_SOURCE_FIND:LD (MOVE_SOURCE_LENGTH),HL
        LD HL,MOVE_DEST_FIND:LD (MOVE_DEST_POINTER),HL
        LD HL,MOVE_DEST_FIND_END-MOVE_DEST_FIND:LD (MOVE_DEST_LENGTH),HL
        CALL DO_MOVE
        RET NZ

        CALL PREPARE_STANDARD_MOVE
        LD HL,REPLACE_SOURCE_FIND:LD (MOVE_SOURCE_POINTER),HL
        LD HL,REPLACE_SOURCE_FIND_END-REPLACE_SOURCE_FIND:LD (MOVE_SOURCE_LENGTH),HL
        LD HL,REPLACE_DEST_FIND:LD (MOVE_DEST_POINTER),HL
        LD HL,REPLACE_DEST_FIND_END-REPLACE_DEST_FIND:LD (MOVE_DEST_LENGTH),HL
        LD A,FILEX_FLAG_REPLACE:LD (MOVE_FLAGS),A
        CALL DO_MOVE
        RET NZ

        CALL PREPARE_STANDARD_MOVE
        LD HL,MOVE_DIRECTORY_SOURCE_FIND:LD (MOVE_SOURCE_POINTER),HL
        LD HL,MOVE_DIRECTORY_SOURCE_FIND_END-MOVE_DIRECTORY_SOURCE_FIND
        LD (MOVE_SOURCE_LENGTH),HL
        LD HL,MOVE_DIRECTORY_DEST_FIND:LD (MOVE_DEST_POINTER),HL
        LD HL,MOVE_DIRECTORY_DEST_FIND_END-MOVE_DIRECTORY_DEST_FIND
        LD (MOVE_DEST_LENGTH),HL
        CALL DO_MOVE
        RET NZ

        ; Замена непустого каталога должна оставить оба объекта без изменений.
        CALL PREPARE_STANDARD_MOVE
        LD HL,EMPTY_DIRECTORY_SOURCE_FIND:LD (MOVE_SOURCE_POINTER),HL
        LD HL,EMPTY_DIRECTORY_SOURCE_FIND_END-EMPTY_DIRECTORY_SOURCE_FIND
        LD (MOVE_SOURCE_LENGTH),HL
        LD HL,NONEMPTY_DIRECTORY_DEST_FIND:LD (MOVE_DEST_POINTER),HL
        LD HL,NONEMPTY_DIRECTORY_DEST_FIND_END-NONEMPTY_DIRECTORY_DEST_FIND
        LD (MOVE_DEST_LENGTH),HL
        LD A,FILEX_FLAG_REPLACE:LD (MOVE_FLAGS),A
        CALL DO_MOVE
        CP FILEX_STATUS_NOT_EMPTY:JP NZ,SEMANTIC_ERROR

        ; Конфликт без флага замены имеет отдельный стабильный статус.
        CALL PREPARE_STANDARD_MOVE
        LD HL,COLLISION_SOURCE_FIND:LD (MOVE_SOURCE_POINTER),HL
        LD HL,COLLISION_SOURCE_FIND_END-COLLISION_SOURCE_FIND
        LD (MOVE_SOURCE_LENGTH),HL
        LD HL,COLLISION_DEST_FIND:LD (MOVE_DEST_POINTER),HL
        LD HL,COLLISION_DEST_FIND_END-COLLISION_DEST_FIND
        LD (MOVE_DEST_LENGTH),HL
        CALL DO_MOVE
        CP FILEX_STATUS_EXISTS:JP NZ,SEMANTIC_ERROR

        ; Попытка поместить CYCLE внутрь CYCLE/CHILD должна быть отвергнута.
        CALL PREPARE_STANDARD_MOVE
        LD HL,CYCLE_DIRECTORY_FIND:LD (MOVE_SOURCE_POINTER),HL
        LD HL,CYCLE_DIRECTORY_FIND_END-CYCLE_DIRECTORY_FIND
        LD (MOVE_SOURCE_LENGTH),HL
        LD HL,CYCLE_RENAMED_FIND:LD (MOVE_DEST_POINTER),HL
        LD HL,CYCLE_RENAMED_FIND_END-CYCLE_RENAMED_FIND
        LD (MOVE_DEST_LENGTH),HL
        LD HL,(CHILD_DIRECTORY_CLUSTER):LD (MOVE_DEST_DIRECTORY),HL
        LD HL,(CHILD_DIRECTORY_CLUSTER+2):LD (MOVE_DEST_DIRECTORY+2),HL
        CALL DO_MOVE
        CP FILEX_STATUS_INVALID_MOVE:JP NZ,SEMANTIC_ERROR
        XOR A
        RET

CAPTURE_DIRECTORY_CLUSTER:
        LD (TEMP_DESTINATION),DE
        CALL FENTRY
        JR Z,.not_found
        LD DE,ENTRY_BUFFER
        CALL TENTRY
        LD HL,(TEMP_DESTINATION)
        LD DE,(ENTRY_BUFFER+26):LD (HL),E:INC HL:LD (HL),D:INC HL
        LD DE,(ENTRY_BUFFER+20)
        LD A,D:AND #0F:LD D,A
        LD (HL),E:INC HL:LD (HL),D
        XOR A
        RET
.not_found:
        LD A,#FD:OR A:RET

PREPARE_STANDARD_MOVE:
        XOR A:LD (MOVE_FLAGS),A
        LD HL,(SOURCE_DIRECTORY_CLUSTER):LD (MOVE_SOURCE_DIRECTORY),HL
        LD HL,(SOURCE_DIRECTORY_CLUSTER+2):LD (MOVE_SOURCE_DIRECTORY+2),HL
        LD HL,(DEST_DIRECTORY_CLUSTER):LD (MOVE_DEST_DIRECTORY),HL
        LD HL,(DEST_DIRECTORY_CLUSTER+2):LD (MOVE_DEST_DIRECTORY+2),HL
        RET

DO_MOVE:
        CALL RESET_FILEX_BLOCK
        LD A,FILEX_OP_MOVE_RENAME:LD (FILEX_BLOCK+FILEX_P_OPERATION),A
        LD A,(MOVE_FLAGS):LD (FILEX_BLOCK+FILEX_P_FLAGS),A
        LD HL,(MOVE_SOURCE_POINTER):LD (FILEX_BLOCK+FILEX_P_BUFFER),HL
        LD HL,(MOVE_SOURCE_LENGTH):LD (FILEX_BLOCK+FILEX_P_LENGTH),HL
        LD HL,(MOVE_DEST_POINTER):LD (FILEX_BLOCK+FILEX_P_AUX),HL
        LD HL,(MOVE_DEST_LENGTH):LD (FILEX_BLOCK+FILEX_P_AUX_LENGTH),HL
        LD HL,(MOVE_SOURCE_DIRECTORY):LD (FILEX_BLOCK+FILEX_P_SOURCE_DIR),HL
        LD HL,(MOVE_SOURCE_DIRECTORY+2):LD (FILEX_BLOCK+FILEX_P_SOURCE_DIR+2),HL
        LD HL,(MOVE_DEST_DIRECTORY):LD (FILEX_BLOCK+FILEX_P_DEST_DIR),HL
        LD HL,(MOVE_DEST_DIRECTORY+2):LD (FILEX_BLOCK+FILEX_P_DEST_DIR+2),HL
        JP CALL_FILEX

TEST_METADATA:
        LD HL,METADATA_FIND:CALL FENTRY:JP Z,SEARCH_ERROR
        LD HL,METADATA_BUFFER,DE,METADATA_BUFFER+1,BC,FILEX_META_SIZE-1
        XOR A:LD (HL),A:LDIR
        LD A,FILEX_META_SIZE:LD (METADATA_BUFFER+FILEX_META_O_SIZE),A
        LD A,FILEX_META_ALLOWED_ATTRS
        LD (METADATA_BUFFER+FILEX_META_O_ATTR_MASK),A
        LD (METADATA_BUFFER+FILEX_META_O_ATTR_VALUE),A
        LD A,FILEX_META_TIME_CREATE|FILEX_META_TIME_ACCESS|FILEX_META_TIME_WRITE
        LD (METADATA_BUFFER+FILEX_META_O_TIME_MASK),A
        LD A,#37:LD (METADATA_BUFFER+FILEX_META_O_CREATE_TENTH),A
        LD HL,#1234:LD (METADATA_BUFFER+FILEX_META_O_CREATE_TIME),HL
        LD HL,#5678:LD (METADATA_BUFFER+FILEX_META_O_CREATE_DATE),HL
        LD HL,#3456:LD (METADATA_BUFFER+FILEX_META_O_ACCESS_DATE),HL
        LD HL,#2345:LD (METADATA_BUFFER+FILEX_META_O_WRITE_TIME),HL
        LD HL,#6789:LD (METADATA_BUFFER+FILEX_META_O_WRITE_DATE),HL
        CALL CALL_SET_METADATA
        RET NZ
        LD A,(METADATA_BUFFER+FILEX_META_O_APPLIED_ATTR)
        CP FILEX_META_ALLOWED_ATTRS:JP NZ,SEMANTIC_ERROR

        ; Изменение времени у read-only объекта запрещено.
        LD HL,METADATA_BUFFER,DE,METADATA_BUFFER+1,BC,FILEX_META_SIZE-1
        XOR A:LD (HL),A:LDIR
        LD A,FILEX_META_SIZE:LD (METADATA_BUFFER+FILEX_META_O_SIZE),A
        LD A,FILEX_META_TIME_WRITE:LD (METADATA_BUFFER+FILEX_META_O_TIME_MASK),A
        LD HL,#1111:LD (METADATA_BUFFER+FILEX_META_O_WRITE_TIME),HL
        LD HL,#2222:LD (METADATA_BUFFER+FILEX_META_O_WRITE_DATE),HL
        CALL CALL_SET_METADATA
        CP FILEX_STATUS_READ_ONLY:JP NZ,SEMANTIC_ERROR

        ; Одной транзакцией снять read-only и установить новое write time.
        LD A,1:LD (METADATA_BUFFER+FILEX_META_O_ATTR_MASK),A
        XOR A:LD (METADATA_BUFFER+FILEX_META_O_ATTR_VALUE),A
        LD A,FILEX_META_TIME_WRITE:LD (METADATA_BUFFER+FILEX_META_O_TIME_MASK),A
        LD HL,#4567:LD (METADATA_BUFFER+FILEX_META_O_WRITE_TIME),HL
        LD HL,#789A:LD (METADATA_BUFFER+FILEX_META_O_WRITE_DATE),HL
        CALL CALL_SET_METADATA
        RET NZ
        LD A,(METADATA_BUFFER+FILEX_META_O_APPLIED_ATTR)
        CP FILEX_META_ALLOWED_ATTRS&~1:JP NZ,SEMANTIC_ERROR
        XOR A
        RET

CALL_SET_METADATA:
        CALL RESET_FILEX_BLOCK
        LD A,FILEX_OP_SET_METADATA:LD (FILEX_BLOCK+FILEX_P_OPERATION),A
        LD HL,METADATA_BUFFER:LD (FILEX_BLOCK+FILEX_P_BUFFER),HL
        LD HL,FILEX_META_SIZE:LD (FILEX_BLOCK+FILEX_P_LENGTH),HL
        JP CALL_FILEX

TEST_FAULT_ROLLBACKS:
        CALL PREPARE_FAULT_ADDRESSES

        ; Отказ записи каталога наступает после разрешённых записей данных/FAT.
        LD HL,FAULT_CATALOG_FIND:CALL FENTRY:JP Z,SEARCH_ERROR
        CALL CAPTURE_CURRENT_DIRECTORY_LBA
        CALL ARM_EXACT_WRITE_FAILURE
        CALL INSTALL_WRITE_FAULT
        LD HL,WRITE_BUFFER:LD (HL),#9A
        LD HL,(CLUSTER_BYTES),DE,0,BC,1
        CALL WRITE_CURRENT
        PUSH AF
        CALL RESTORE_WRITE_FAULT
        POP AF
        LD (RESULT_FAULT_CAT),A
        OR A:JP Z,SEMANTIC_ERROR
        LD A,(WRITE_FAULT_HIT):OR A:JP Z,SEMANTIC_ERROR
        LD HL,FAULT_CATALOG_FIND
        LD DE,(CLUSTER_BYTES)
        CALL VERIFY_FILE_SIZE_LOW
        RET NZ

        ; SET_METADATA не должен публиковать изменённую ENTRY при отказе сектора.
        LD HL,FAULT_METADATA_FIND:CALL FENTRY:JP Z,SEARCH_ERROR
        CALL CAPTURE_CURRENT_DIRECTORY_LBA
        CALL ARM_EXACT_WRITE_FAILURE
        CALL INSTALL_WRITE_FAULT
        LD HL,METADATA_BUFFER,DE,METADATA_BUFFER+1,BC,FILEX_META_SIZE-1
        XOR A:LD (HL),A:LDIR
        LD A,FILEX_META_SIZE:LD (METADATA_BUFFER),A
        LD A,FILEX_META_ALLOWED_ATTRS
        LD (METADATA_BUFFER+FILEX_META_O_ATTR_MASK),A
        LD (METADATA_BUFFER+FILEX_META_O_ATTR_VALUE),A
        CALL CALL_SET_METADATA
        PUSH AF
        CALL RESTORE_WRITE_FAULT
        POP AF
        LD (RESULT_FAULT_META),A
        CP FILEX_STATUS_MEDIA:JP NZ,SEMANTIC_ERROR
        LD A,(WRITE_FAULT_HIT):OR A:JP Z,SEMANTIC_ERROR

        ; Первый отказ записи FAT при росте пустого файла не создаёт ложный EOF.
        LD HL,FAULT_FAT_FIND:CALL FENTRY:JP Z,SEARCH_ERROR
        CALL ARM_FAT_WRITE_FAILURE
        CALL INSTALL_WRITE_FAULT
        LD HL,FAULT_FAT_FIND,BC,1,DE,0
        CALL SET_EOF_NAMED
        PUSH AF
        CALL RESTORE_WRITE_FAULT
        POP AF
        LD (RESULT_FAULT_FAT),A
        OR A:JP Z,SEMANTIC_ERROR
        LD A,(WRITE_FAULT_HIT):OR A:JP Z,SEMANTIC_ERROR
        LD HL,FAULT_FAT_FIND,DE,0
        CALL VERIFY_FILE_SIZE_LOW
        RET NZ

        ; Отказ FSInfo после данных и FAT обязан вернуть исходный размер.
        LD HL,FAULT_FSINFO_FIND:CALL FENTRY:JP Z,SEARCH_ERROR
        LD HL,(FAULT_FSINFO_LBA):LD (WRITE_FAIL_LBA),HL
        LD HL,(FAULT_FSINFO_LBA+2):LD (WRITE_FAIL_LBA+2),HL
        CALL ARM_EXACT_WRITE_FAILURE
        CALL INSTALL_WRITE_FAULT
        LD HL,(CLUSTER_BYTES),DE,1:ADD HL,DE
        LD B,H:LD C,L
        LD HL,FAULT_FSINFO_FIND,DE,0
        CALL SET_EOF_NAMED
        PUSH AF
        CALL RESTORE_WRITE_FAULT
        POP AF
        LD (RESULT_FAULT_FSINFO),A
        OR A:JP Z,SEMANTIC_ERROR
        LD A,(WRITE_FAULT_HIT):OR A:JP Z,SEMANTIC_ERROR
        LD HL,FAULT_FSINFO_FIND
        LD DE,(CLUSTER_BYTES)
        CALL VERIFY_FILE_SIZE_LOW
        RET NZ
        XOR A
        RET

; Вход: HL — запрос, DE — ожидаемый младший размер; старшее слово равно нулю.
VERIFY_FILE_SIZE_LOW:
        LD (TEMP_EXPECTED),DE
        CALL FENTRY
        JR Z,.not_found
        LD DE,ENTRY_BUFFER:CALL TENTRY
        LD HL,(ENTRY_BUFFER+28),DE,(TEMP_EXPECTED)
        OR A:SBC HL,DE:JR NZ,.bad
        LD HL,(ENTRY_BUFFER+30)
        LD A,H:OR L:JR NZ,.bad
        XOR A
        RET
.not_found:
        LD A,#FD:OR A:RET
.bad:
        JP SEMANTIC_ERROR

PREPARE_FAULT_ADDRESSES:
        CALL CORE_PAGE_IN
        ; Начало всех FAT = ADDTOP + reserved(SFAT).
        LD HL,(FILEX_TEST_WDOS.ADDTOP)
        LD DE,(FILEX_TEST_WDOS.ADDTOP+2)
        LD BC,(FILEX_TEST_WDOS.SFAT)
        ADD HL,BC:JR NC,.fat_begin_ready
        INC DE
.fat_begin_ready:
        LD (FAULT_FAT_BEGIN),HL:LD (FAULT_FAT_BEGIN+2),DE
        ; Конец FAT-области = ADDTOP + SDFAT, то есть начало данных.
        LD HL,(FILEX_TEST_WDOS.ADDTOP)
        LD DE,(FILEX_TEST_WDOS.ADDTOP+2)
        LD BC,(FILEX_TEST_WDOS.SDFAT)
        ADD HL,BC:JR NC,.fat_end_low_ready
        INC DE
.fat_end_low_ready:
        LD BC,(FILEX_TEST_WDOS.SDFAT+2)
        EX DE,HL:ADD HL,BC:EX DE,HL
        LD (FAULT_FAT_END),HL:LD (FAULT_FAT_END+2),DE
        LD HL,(FILEX_TEST_WDOS.FSINF)
        LD (FAULT_FSINFO_LBA),HL
        LD HL,(FILEX_TEST_WDOS.FSINF+2)
        LD (FAULT_FSINFO_LBA+2),HL
        CALL CORE_PAGE_OUT
        XOR A
        RET

CAPTURE_CURRENT_DIRECTORY_LBA:
        CALL CORE_PAGE_IN
        LD HL,(FILEX_TEST_WDOS.LLHL):LD (WRITE_FAIL_LBA),HL
        LD HL,(FILEX_TEST_WDOS.LLHL+2):LD (WRITE_FAIL_LBA+2),HL
        CALL CORE_PAGE_OUT
        RET

ARM_EXACT_WRITE_FAILURE:
        LD A,FAIL_MODE_EXACT:JR ARM_WRITE_FAILURE
ARM_FAT_WRITE_FAILURE:
        LD A,FAIL_MODE_FAT
ARM_WRITE_FAILURE:
        LD (WRITE_FAIL_MODE),A
        LD A,1:LD (WRITE_FAIL_ARMED),A
        XOR A:LD (WRITE_FAULT_HIT),A
        RET

INSTALL_WRITE_FAULT:
        CALL CORE_PAGE_IN
        LD HL,DRIVER_SDD_JUMP,DE,WRITE_JUMP_ORIGINAL,BC,3
        LDIR
        CALL PATCH_WRITE_JUMP
        CALL CORE_PAGE_OUT
        RET

RESTORE_WRITE_FAULT:
        CALL CORE_PAGE_IN
        CALL UNPATCH_WRITE_JUMP
        CALL CORE_PAGE_OUT
        RET

PATCH_WRITE_JUMP:
        LD HL,DRIVER_SDD_JUMP
        LD (HL),#C3:INC HL
        LD DE,FAULTING_SDDSE
        LD (HL),E:INC HL:LD (HL),D
        RET

UNPATCH_WRITE_JUMP:
        LD HL,WRITE_JUMP_ORIGINAL,DE,DRIVER_SDD_JUMP,BC,3
        LDIR
        RET

; Обёртка отказывает ровно один подходящий SDDSE, затем пропускает откат.
FAULTING_SDDSE:
        PUSH AF,BC,DE,HL
        LD A,(WRITE_FAIL_ARMED):OR A:JR Z,.pass
        CALL SHOULD_FAIL_CURRENT_WRITE
        JR Z,.pass
        XOR A:LD (WRITE_FAIL_ARMED),A
        INC A:LD (WRITE_FAULT_HIT),A
        POP HL,DE,BC,AF
        LD A,#EE:LD (DRIVER_ABT),A:OR A
        RET
.pass:
        CALL UNPATCH_WRITE_JUMP
        POP HL,DE,BC,AF
        CALL DRIVER_SDD_JUMP
        PUSH AF,BC,DE,HL
        CALL PATCH_WRITE_JUMP
        POP HL,DE,BC,AF
        RET

SHOULD_FAIL_CURRENT_WRITE:
        LD A,(WRITE_FAIL_MODE):CP FAIL_MODE_FAT:JR Z,.fat
        LD HL,(DRIVER_BLKNUM),DE,(WRITE_FAIL_LBA)
        OR A:SBC HL,DE:JR NZ,.no
        LD HL,(DRIVER_BLKNUM+2),DE,(WRITE_FAIL_LBA+2)
        OR A:SBC HL,DE:JR NZ,.no
        LD A,1:OR A:RET
.fat:
        ; Текущий сектор находится не раньше начала диапазона.
        LD HL,(DRIVER_BLKNUM+2),DE,(FAULT_FAT_BEGIN+2)
        OR A:SBC HL,DE:JR C,.no:JR NZ,.below_end
        LD HL,(DRIVER_BLKNUM),DE,(FAULT_FAT_BEGIN)
        OR A:SBC HL,DE:JR C,.no
.below_end:
        ; Текущий сектор находится раньше исключающей границы диапазона.
        LD HL,(DRIVER_BLKNUM+2),DE,(FAULT_FAT_END+2)
        OR A:SBC HL,DE:JR C,.yes:JR NZ,.no
        LD HL,(DRIVER_BLKNUM),DE,(FAULT_FAT_END)
        OR A:SBC HL,DE:JR C,.yes
.no:
        XOR A:RET
.yes:
        LD A,1:OR A:RET

INSTALL_READ_COUNTER:
        XOR A:LD (READ_CALLS),A
        CALL CORE_PAGE_IN
        LD HL,DRIVER_RDD_JUMP,DE,READ_JUMP_ORIGINAL,BC,3
        LDIR
        CALL PATCH_READ_JUMP
        CALL CORE_PAGE_OUT
        RET

RESTORE_READ_COUNTER:
        CALL CORE_PAGE_IN
        CALL UNPATCH_READ_JUMP
        CALL CORE_PAGE_OUT
        RET

PATCH_READ_JUMP:
