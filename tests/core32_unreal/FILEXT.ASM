        LD (HL),#C3:INC HL
        LD DE,COUNTED_RDDSE
        LD (HL),E:INC HL:LD (HL),D
        RET

UNPATCH_READ_JUMP:
        LD HL,READ_JUMP_ORIGINAL,DE,DRIVER_RDD_JUMP,BC,3
        LDIR
        RET

COUNTED_RDDSE:
        PUSH AF,BC,DE,HL
        LD A,(READ_CALLS):INC A:LD (READ_CALLS),A
        CALL UNPATCH_READ_JUMP
        POP HL,DE,BC,AF
        CALL DRIVER_RDD_JUMP
        PUSH AF,BC,DE,HL
        CALL PATCH_READ_JUMP
        POP HL,DE,BC,AF
        RET

